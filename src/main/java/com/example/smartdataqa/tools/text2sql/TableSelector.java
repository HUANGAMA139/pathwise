package com.example.smartdataqa.tools.text2sql;

import java.util.List;

/**
 * 迭代 19 · <b>表筛选</b>：给一个自然语言问题，挑出该注入表结构的那些表。
 *
 * <h3>为什么需要它</h3>
 * 迭代 18 是把<b>整个库的表结构</b>拼进 prompt 的。5 张表时没问题（约 2100 字符），
 * 但这显然不可扩展，两个代价都会随着表数增长：
 * <ul>
 *   <li><b>token 爆</b>——几百张表就是几十万字符，物理上塞不下；</li>
 *   <li><b>注意力被稀释</b>——迭代 18 已经看到模型会挑错列、挑错表；
 *       候选越多，挑错的概率越大（这一点 迭代 22 可以量）。</li>
 * </ul>
 * 所以标准做法是：<b>先从「表目录」里召回少量最相关的表，再只把这几张的结构注入。</b>
 * 这一步在 Text2SQL 里叫 schema linking / table selection。
 *
 * <h3>本轮最要紧的一句话：这活儿 迭代 16 已经干过一遍了</h3>
 * 把两天的流水线摆在一起看，只有<b>被检索的东西</b>变了：
 * <pre>
 *                 迭代 16（文档支路）              迭代 19（表筛选）
 *   检索单位      文档片段（19 个 chunk）          表目录条目（20 条，一表一条）
 *   上面标什么    出处（哪份文档）                 表名
 *   渠道          BM25 + 向量                      BM25 + 向量     ← 一样
 *   融合          RRF                              RRF             ← 一样
 *   拿到之后干嘛  拼进 prompt 当材料               把这几张表的结构拼进 prompt
 * </pre>
 * <b>{@code Bm25Index} 和 {@code RrfDocumentJoiner} 两个类，本轮一行都没改。</b>
 * 这不是「碰巧能复用」——是因为当初把它们写成了「跑在 {@code List<Document>} 上」，
 * 而<b>「Document」本来就只是个「有 id、有正文、可以被排序」的东西</b>，
 * 它是不是「文档片段」并不重要。
 *
 * <p>面试时这个例子比「我实现了 BM25」值钱得多：它证明你理解的是<b>检索这个动作</b>，
 * 不是「照着教程给文档做检索」。
 *
 * <h3>两路为什么都要：和 迭代 16 同一个判断</h3>
 * <pre>
 *   BM25 强在  精确标识符：表名 sales_orders、列名 refund_amount、型号 XR-2000B
 *   向量 强在  口语化说法：「这个季度卖了多少钱」和「当期销售订单」字面几乎不重合
 * </pre>
 * 两者互补，所以融合；融合用 RRF 而不是分数加权，理由同 迭代 16——
 * <b>BM25 分和余弦相似度不可比，直接比大小等于让 BM25 的量纲决定一切。</b>
 *
 * <h3>一个必须守住的约束：不能污染 {@code vector_store}</h3>
 * 表目录的向量<b>绝对不能灌进 RAG 那张 pgvector 表</b>。
 * 迭代 14—17 的所有基线数字（19 个片段、hit@1 0.87 …）都建立在
 * 「那张表里恰好只有 19 个文档片段」之上，多灌 20 条表目录进去，
 * 文档检索的结果会变，<b>所有历史基线当场作废，而且不会报错</b>。
 * 所以这里把目录向量放在内存里算（20 张表而已，两批调用），不碰任何持久化设施。
 *
 * <h3>返回 null 与返回空列表的区别</h3>
 * {@code select} 返回<b>空列表</b>表示「什么都没选中」——调用方必须把它当成异常情况处理
 * （空表结构是最坏的静默失败：模型会以为这个库是空的）。正常不该出现。
 */
public interface TableSelector {

    /**
     * 选出该注入的表。
     *
     * @param question 用户原始问题
     * @param topK     最多选几张
     * @return 表名列表，按相关度从高到低。<b>可能为空</b>，调用方要处理
     */
    List<String> select(String question, int topK);
}
