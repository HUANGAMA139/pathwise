package com.example.smartdataqa.rag.pipeline;

/**
 * 迭代 26 · <b>第一层：改写器</b>。对应 Spring AI 的 {@code QueryTransformer} 槽位。
 *
 * <h3>为什么这一层单独存在</h3>
 * 检索质量的上限，在检索之前就定了一半——<b>拿用户的原始口语去检索，本来就吃亏</b>。
 * 用户问「退了货以后钱什么时候从销售额里减掉」，而文档里写的是「退货金额扣减时点」，
 * 中间那段语义距离，是这一层要补的。
 *
 * <p>{@code DocumentTool.search} 的注释里早就写了伏笔：
 * 「{@code query} 通常是用户的原始问题，<b>迭代 22 的查询重写会改这个环节</b>」。
 *
 * <h3>为什么不用 Spring AI 的 {@code QueryTransformer}</h3>
 * <b>不是不想用，是没法核实。</b>项目锁的是 1.1.0，而这个类在 1.1.0 里的确切包名与签名
 * 我无法在沙箱里验证（拉不到源码）。项目已经被「官方文档与 1.1.0 实际签名不符」坑过三次
 * （见技术坑表），再来一次就是第 4 次「交付后 mvn 报找不到符号」。
 * <b>所以新增的两层用项目自己的接口</b>——语义上仍是「五件套」的对应层，只是接口是自己定的。
 * 要换成框架接口时，先核实包名，再改这两个文件即可。
 */
public interface QueryRewriter {

    /**
     * 把用户问题改写成更适合检索的查询。
     *
     * <p>实现必须保证<b>改写失败时退回原问题</b>——宁可少改一次，也不能让链路挂掉
     * （同 迭代 9 路由降级、迭代 19 表筛选降级）。
     */
    String rewrite(String question);

    /** 档位名，进消融表。 */
    String name();
}
